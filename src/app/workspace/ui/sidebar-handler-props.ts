import type { WorkspaceHandlers } from "../handlers/workspace-handlers";

/** The sidebar's callbacks, all taken from the workspace's action objects. */
export function sidebarHandlerProps(h: WorkspaceHandlers, notesEnabled: boolean | undefined) {
  return {
    onSelectWorkspace: h.projects.selectWorkspace,
    onOpenFilesSearch: h.surfaces.findInProject,
    onSelectSession: h.sessionOpeners.selectHistory,
    onSelectRemoteSession: h.newSessions.selectRemoteSession,
    onRemoteSessionDeleted: h.tabClose.closeDeletedRemoteSession,
    onPrefetchSession: h.prefetchSession,
    onSessionNavigationOrder: h.navigation.setSessionNavigationOrder,
    onPlaceSessionOnPane: h.tabs.placeSession,
    onRenameSession: h.history.rename,
    onArchiveSession: h.history.archive,
    onArchiveSessions: h.history.archiveMany,
    onPinSession: h.history.pin,
    onPinSessions: h.history.pinMany,
    onSetSessionLinkedWorkItem: h.history.setLinkedWorkItem,
    onDeleteSession: h.history.delete,
    onDeleteSessions: h.history.deleteMany,
    onOpenFile: h.files.open,
    onOpenTerminal: h.terminals.open,
    onFileMoved: h.files.moved,
    onFileDeleted: h.files.deleted,
    onGoBack: h.surfaces.railBack,
    onGoForward: h.surfaces.railForward,
    onOpenDiff: h.tabs.openWorkingTreeDiff,
    onOpenAllChanges: h.tabs.openAllChanges,
    onOpenCommit: h.tabs.openCommit,
    onSelectAgent: h.workerPanes.selectLiveAgent,
    onStopAgent: h.workerPanes.closeLiveAgent,
    onSelectProject: h.projects.select,
    onOpenProject: h.projects.pick,
    onRemoveProject: h.projects.remove,
    onNew: h.newSessions.newSession,
    onNewTerminal: h.terminals.openNew,
    onSearch: h.surfaces.openSearch,
    onOpenInbox: h.surfaces.openInbox,
    onOpenInboxItem: h.linkedPanels.open,
    onOpenNotes: notesEnabled ? h.surfaces.openNotes : undefined,
    onOpenAutomations: h.surfaces.openAutomations,
    onGoToFile: h.surfaces.goToFile,
    onToggleProjectRail: h.navigation.toggleProjectRail,
    onOpenSettings: h.surfaces.openSettingsHome,
    onOpenNotificationSettings: h.surfaces.openNotificationSettings,
    onSelectSettingsSection: h.surfaces.selectSettingsSection,
    onCloseSettings: h.surfaces.closeSettings,
    onOpenWhatsNew: h.surfaces.openWhatsNew,
  };
}
